#!/usr/bin/env python3
"""The names an image may import, from openkal's SURFACE.txt, as the lines
libokrun binds: run/src/surface.inc (every interface but openkal.space) and
run/src/surface_space.inc (openkal.space, bound where the implementation
provides it). `--check' fails when the committed files differ."""
import pathlib, sys
here = pathlib.Path(__file__).resolve().parent.parent
surface = pathlib.Path(sys.argv[sys.argv.index('--surface') + 1]) if '--surface' in sys.argv else here.parent / 'openkal' / 'SURFACE.txt'
groups, current = {}, None
for line in surface.read_text().splitlines():
    if line.startswith('# openkal.'):
        current = line.split()[1]
        groups.setdefault(current, [])
    elif line.startswith('kal_') and current:
        groups[current].append(line.strip())
# The arguments and the image's own name are the runner's to answer (SPEC
# 12.3); every other name is the implementation's.
own = {'kal_env_arg_count', 'kal_env_arg', 'kal_env_image'}
callbacks = {'kal_task_start', 'kal_task_start_sized'}
def emit(names):
    out = ['// GENERATED by tools/gen-surface.py from openkal SURFACE.txt. Do not edit.']
    for n in names:
        kind = 'OKRUN_OWN' if n in own else 'OKRUN_CALLBACK' if n in callbacks else 'OKRUN_BIND'
        out.append(f'{kind}({n})')
    return '\n'.join(out) + '\n'
main = [n for g, ns in groups.items() if g != 'openkal.space' for n in ns]
space = groups.get('openkal.space', [])
files = { here / 'run/src/surface.inc': emit(main), here / 'run/src/surface_space.inc': emit(space) }
bad = False
for path, text in files.items():
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != text:
            print(f'{path.relative_to(here)} is not what SURFACE.txt says; run tools/gen-surface.py'); bad = True
    else:
        path.write_text(text)
sys.exit(1 if bad else 0)
